// Generates src/lib/atomic/nuclideData.generated.js from the NUBASE2020 text file.
// Usage: node scripts/gen-nuclide-data.mjs <path-to-nubase_4.mas20.txt>
// Source: F.G. Kondev, M. Wang, W.J. Huang, S. Naimi, G. Audi, Chin. Phys. C 45, 030001 (2021)
// (the NUBASE2020 evaluation, distributed as "nubase_4.mas20.txt" by AMDC/IAEA; the copy used
// here came from the Python wheel "nucleardatapy" 1.0.2, file data/nuclei/masses/AME/2020_nubase_4.mas20.txt).
// Rules: ground states only (ZZZi with i = 0); entries whose mass excess is flagged "#" (extrapolated
// from systematics, i.e. NEVER observed) are dropped. Half-life converted to seconds, 3 significant digits.
import fs from "node:fs";
const src = process.argv[2];
if (!src) { console.error("usage: node scripts/gen-nuclide-data.mjs <nubase file>"); process.exit(1); }
const UNIT = { ys: 1e-24, zs: 1e-21, as: 1e-18, fs: 1e-15, ps: 1e-12, ns: 1e-9, us: 1e-6, ms: 1e-3, s: 1, m: 60, h: 3600, d: 86400, y: 3.15576e7,
  ky: 3.15576e10, My: 3.15576e13, Gy: 3.15576e16, Ty: 3.15576e19, Py: 3.15576e22, Ey: 3.15576e25, Zy: 3.15576e28, Yy: 3.15576e31 };
const byZ = {};
let skippedExtrap = 0;
for (const line of fs.readFileSync(src, "utf8").split("\n")) {
  if (!line || line.startsWith("#")) continue;
  const A = parseInt(line.slice(0, 3), 10);
  const zzzi = line.slice(4, 8);
  const Z = parseInt(zzzi.slice(0, 3), 10);
  const i = zzzi[3];
  if (!Number.isFinite(A) || i !== "0" || Z < 1) continue;
  const mass = line.slice(18, 31);
  const tfield = line.slice(69, 78).trim();
  // Observed = measured mass, OR a measured (non-"#") half-life even when the mass is still systematic.
  const measuredHalfLife = tfield !== "" && tfield !== "p-unst" && !tfield.includes("#") && !mass.trim().startsWith("*");
  if (mass.includes("#") && !measuredHalfLife) { skippedExtrap += 1; continue; }
  const unit = line.slice(78, 80).trim();
  let hl;
  if (tfield === "stbl") hl = 0;
  else if (tfield === "p-unst" || tfield === "") hl = -1; // observed, no measured half-life: particle unbound
  else {
    const v = parseFloat(tfield.replace("#", ""));
    const u = UNIT[unit];
    if (!Number.isFinite(v) || !u) { hl = -1; } else hl = Number((v * u).toPrecision(3));
  }
  const m = /IS=([\d.]+)/.exec(line.slice(119));
  const ab = m ? Number(m[1]) : 0;
  (byZ[Z] ??= []).push(ab ? [A, hl, ab] : [A, hl]);
}
let out = `// GENERATED by scripts/gen-nuclide-data.mjs - do not edit by hand.\n`;
out += `// Source: NUBASE2020, F.G. Kondev, M. Wang, W.J. Huang, S. Naimi, G. Audi, Chin. Phys. C 45, 030001 (2021).\n`;
out += `// Ground states only. Nuclides whose mass is extrapolated ("#" in NUBASE2020) AND have no measured half-life (never observed) are excluded.\n`;
out += `// Row format per nuclide: [massNumber, halfLifeSeconds, naturalAbundancePercent?]\n`;
out += `//   halfLifeSeconds: 0 = stable (stbl), -1 = observed but unbound / no measured half-life, otherwise seconds (1 y = 3.15576e7 s).\n`;
out += `// Excluded as extrapolated (never observed): ${skippedExtrap} ground-state entries.\n`;
out += `export const NUBASE_YEAR = 2020;\nexport const NUCLIDE_ROWS = {\n`;
for (const z of Object.keys(byZ).map(Number).sort((a, b) => a - b)) {
  out += `  ${z}: ${JSON.stringify(byZ[z].sort((a, b) => a[0] - b[0]))},\n`;
}
out += `};\n`;
fs.writeFileSync(new URL("../src/lib/atomic/nuclideData.generated.js", import.meta.url), out);
console.log("elements", Object.keys(byZ).length, "nuclides", Object.values(byZ).reduce((s, r) => s + r.length, 0), "skipped extrapolated", skippedExtrap);
