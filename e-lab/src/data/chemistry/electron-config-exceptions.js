// Curated ground-state electron-configuration exceptions to naive Aufbau
// filling. This is the ONLY place irregular configurations are special
// cased — buildConfiguration.js's algorithmic filler stays a clean,
// general implementation of the Madelung rule and is never patched inline.
//
// Each entry is a full list of {n, l, electrons} subshell occupations
// (not just the anomalous part) so the engine can use it directly in place
// of the algorithmic result, no merging logic required.
//
// l: 0 = s, 1 = p, 2 = d, 3 = f
//
// Sources: widely accepted gas-phase ground-state configurations (NIST
// Atomic Spectra Database conventions). The lawrencium (103) entry follows
// the 2021 IUPAC-endorsed [Rn] 5f14 7s2 7p1 assignment rather than the
// older, incorrect 6d1 prediction.

function core(...pairs) {
  return pairs.map(([n, l, electrons]) => ({ n, l, electrons }));
}

